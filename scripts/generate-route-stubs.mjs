// Generates the Nitro route files that mount the ported handlers in server/handlers.
// Each `server/handlers/<area>/**/route.ts` gets a stub under server/api or server/routes.
// Re-run after adding or removing a handler: `bun run routes:generate`.
import { mkdirSync, readdirSync, rmSync, statSync, writeFileSync, existsSync, readFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const MARK = '// Generated by scripts/generate-route-stubs.mjs. Do not edit.'
const AREAS = [
  { from: 'server/handlers/api', to: 'server/api' },
  { from: 'server/handlers/jmap', to: 'server/routes/jmap' },
  { from: 'server/handlers/mcp', to: 'server/routes/mcp' },
  { from: 'server/handlers/well-known', to: 'server/routes/.well-known' },
]

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) walk(path, out)
    else out.push(path)
  }
  return out
}

function clean(dir) {
  if (!existsSync(dir)) return
  for (const file of walk(dir)) if (readFileSync(file, 'utf8').startsWith(MARK)) rmSync(file)
}

let count = 0
for (const area of AREAS) {
  clean(join(root, area.to))
  for (const file of walk(join(root, area.from)).filter(f => /[\\/]route\.tsx?$/.test(f))) {
    const segments = relative(join(root, area.from), dirname(file)).split(/[\\/]/).filter(Boolean)
    const catchAll = []
    const mapped = segments.map((segment) => {
      const optional = segment.match(/^\[\[\.\.\.(.+)\]\]$/)
      const rest = optional ?? segment.match(/^\[\.\.\.(.+)\]$/)
      if (rest) { catchAll.push(rest[1]); return `[...${rest[1]}]` }
      return segment
    })
    const targets = []
    const base = join(root, area.to, ...mapped)
    // Nitro's `[...x]` does not match the bare parent path; Next's optional catch-all does.
    if (segments.at(-1)?.startsWith('[[...')) targets.push(join(root, area.to, ...mapped.slice(0, -1), 'index.ts'))
    targets.push(mapped.length ? `${base}.ts` : join(base, 'index.ts'))
    const importPath = '#handlers/' + relative(join(root, 'server/handlers'), file).replace(/\\/g, '/').replace(/\.tsx?$/, '')
    const opts = catchAll.length ? `, { catchAll: ${JSON.stringify(catchAll)} }` : ''
    for (const target of targets) {
      mkdirSync(dirname(target), { recursive: true })
      writeFileSync(target, `${MARK}\nimport * as route from '${importPath}'\n\nexport default defineNextRoute(route${opts})\n`)
      count++
    }
  }
}
console.log(`Generated ${count} route stubs`)
